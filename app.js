const root = document.documentElement;
const languageToggle = document.getElementById("languageToggle");
const themeToggle = document.getElementById("themeToggle");
const menuToggle = document.getElementById("menuToggle");
const nav = document.querySelector(".nav");

let lang = localStorage.getItem("portfolio-lang") || "en";
let theme = localStorage.getItem("portfolio-theme") || "dark";

function applyLanguage() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  languageToggle.textContent = lang === "en" ? "ES" : "EN";
}
function applyTheme() {
  root.dataset.theme = theme;
  themeToggle.textContent = theme === "dark" ? "☀" : "☾";
}
languageToggle.addEventListener("click", () => {
  lang = lang === "en" ? "es" : "en";
  localStorage.setItem("portfolio-lang", lang);
  applyLanguage();
});
themeToggle.addEventListener("click", () => {
  theme = theme === "dark" ? "light" : "dark";
  localStorage.setItem("portfolio-theme", theme);
  applyTheme();
});
menuToggle.addEventListener("click", () => {
  const open = nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
nav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => {
  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}));
document.getElementById("printCv").addEventListener("click", () => window.print());
document.getElementById("year").textContent = new Date().getFullYear();

const observed = [...document.querySelectorAll("main section[id]")];
const links = [...document.querySelectorAll(".nav a")];
const observer = new IntersectionObserver(entries => {
  const visible = entries.filter(e => e.isIntersecting).sort((a,b) => b.intersectionRatio - a.intersectionRatio)[0];
  if (!visible) return;
  links.forEach(link => link.classList.toggle("active", link.getAttribute("href") === "#" + visible.target.id));
}, { rootMargin: "-25% 0px -60% 0px", threshold: [0.05, 0.2, 0.5] });
observed.forEach(section => observer.observe(section));

applyLanguage();
applyTheme();
