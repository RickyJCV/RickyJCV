const root=document.documentElement;
const languageToggle=document.getElementById("languageToggle");
const themeToggle=document.getElementById("themeToggle");
const menuToggle=document.getElementById("menuToggle");
const nav=document.getElementById("nav");
const printCv=document.getElementById("printCv");

let lang=localStorage.getItem("portfolio-lang") || (navigator.language && navigator.language.toLowerCase().startsWith("es") ? "es":"en");
let theme=localStorage.getItem("portfolio-theme") || "dark";

function applyLanguage(){
  root.lang=lang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const value=translations[lang][el.dataset.i18n];
    if(value) el.textContent=value;
  });
  languageToggle.textContent=lang==="es" ? "EN":"ES";
  languageToggle.setAttribute("aria-label",lang==="es" ? "Cambiar a inglés":"Switch to Spanish");
}
function applyTheme(){
  root.dataset.theme=theme;
  themeToggle.textContent=theme==="dark" ? "☀":"☾";
}
languageToggle.addEventListener("click",()=>{
  lang=lang==="es" ? "en":"es";
  localStorage.setItem("portfolio-lang",lang);
  applyLanguage();
});
themeToggle.addEventListener("click",()=>{
  theme=theme==="dark" ? "light":"dark";
  localStorage.setItem("portfolio-theme",theme);
  applyTheme();
});
menuToggle.addEventListener("click",()=>{
  const isOpen=nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded",String(isOpen));
});
nav.querySelectorAll("a").forEach(link=>link.addEventListener("click",()=>{
  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded","false");
}));
printCv.addEventListener("click",()=>window.print());
document.getElementById("year").textContent=new Date().getFullYear();

const sections=[...document.querySelectorAll("main section[id]")];
const navLinks=[...document.querySelectorAll(".nav a")];
const activeObserver=new IntersectionObserver(entries=>{
  const visible=entries.filter(e=>e.isIntersecting).sort((a,b)=>b.intersectionRatio-a.intersectionRatio)[0];
  if(!visible) return;
  navLinks.forEach(link=>link.classList.toggle("active",link.getAttribute("href")==="#"+visible.target.id));
},{rootMargin:"-24% 0px -62% 0px",threshold:[.05,.2,.4]});
sections.forEach(section=>activeObserver.observe(section));

const revealTargets=document.querySelectorAll(".section-header,.card,.experience-item,.project-card,.contact-panel");
revealTargets.forEach(el=>el.classList.add("reveal"));
const revealObserver=new IntersectionObserver(entries=>{
  entries.forEach(entry=>{
    if(entry.isIntersecting){
      entry.target.classList.add("visible");
      revealObserver.unobserve(entry.target);
    }
  });
},{threshold:.1,rootMargin:"0px 0px -50px 0px"});
revealTargets.forEach(el=>revealObserver.observe(el));

applyLanguage();
applyTheme();
